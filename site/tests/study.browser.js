async (page) => {
  const check = (condition, label) => { if (!condition) throw new Error(label); };
  const base = await page.evaluate(() => new URL('./', location.href).href);
  const sectionControl = {
    async selectOption(value) {
      const headings = page.locator('main > h2[id]');
      const id = typeof value === 'string' ? value : value.label || await headings.nth(value.index).getAttribute('id');
      await page.waitForFunction(() => Math.abs(parseFloat(document.querySelector('main').style.getPropertyValue('--lesson-offset')) - document.querySelector('.lesson-toolbar').getBoundingClientRect().height - 70) < 1);
      await page.evaluate(id => {
        const heading = document.getElementById(id);
        if (!heading) throw new Error('Missing section: ' + id);
        location.hash = encodeURIComponent(id);
        heading.scrollIntoView({block: 'start'});
        window.dispatchEvent(new HashChangeEvent('hashchange'));
      }, id);
      await page.waitForFunction(id => document.querySelector('.lesson-outline [aria-current="location"]')?.dataset.section === id, id, {timeout: 5000}).catch(() => { throw new Error('Section link did not settle: ' + id); });
    },
    inputValue: () => page.locator('.lesson-outline [aria-current="location"]').getAttribute('data-section'),
    locator: () => page.locator('main > h2[id]')
  };
  await page.evaluate(() => {
    sessionStorage.removeItem('nodefusion-study-height');
    sessionStorage.setItem('nodefusion-study-side', 'false');
  });
  await page.setViewportSize({width: 1440, height: 900});
  await page.goto(base + 'ch3/rcore.html');
  const sections = sectionControl;
  await sections.selectOption('让出与选择下一个任务');
  await page.evaluate(() => window.scrollBy(0, 90));
  const original = await page.evaluate(() => window.scrollY);
  await sections.selectOption('运行观察');
  check(await page.locator('main > h2[id="运行观察"]').isVisible(), 'Section link reaches run observation');
  const reading = await page.evaluate(() => window.scrollY);
  const reportLink = page.locator('.lesson-toolbar').getByRole('link', {name: '运行报告', exact: true});
  await reportLink.click();
  const region = page.getByRole('region', {name: '阅读资料'});
  check(await region.isVisible(), 'Report opens in reading workspace');
  await page.frameLocator('iframe[title="运行报告"]').locator('#panel-functions').waitFor({state: 'attached'});
  await page.frameLocator('iframe[title="运行报告"]').locator('#panel-functions.on').waitFor();
  check(await page.locator('iframe[title="运行报告"]').evaluate(frame => frame.contentDocument.querySelector('nav.tabs button[data-tab="functions"]').getAttribute('aria-current') === 'page'), 'Report opens at function trace');
  check(Math.abs(await page.evaluate(() => window.scrollY) - reading) < 2, 'Report keeps reading position');
  const desktopReport = page.frameLocator('iframe[title="运行报告"]');
  await desktopReport.locator('.study-run-information').waitFor();
  check(!(await desktopReport.locator('.study-run-information').evaluate(el => el.open)), 'Desktop embeds leave metadata collapsed and data visible');
  await desktopReport.getByText('运行信息与时间轴', {exact: true}).click();
  check(await desktopReport.locator('.study-run-information').evaluate(el => el.open), 'Desktop run information can be expanded');
  await page.setViewportSize({width: 900, height: 900});
  check(await desktopReport.locator('.study-run-information').evaluate(el => el.open), 'Resizing preserves explicit metadata choice');
  await page.setViewportSize({width: 1440, height: 900});
  await desktopReport.getByText('运行信息与时间轴', {exact: true}).click();
  check(await desktopReport.locator('#play').isVisible(), 'Playback remains available with metadata closed');
  const resize = page.getByRole('separator', {name: '调整报告高度'});
  await resize.focus();
  await page.keyboard.press('ArrowDown');
  check(await resize.getAttribute('aria-valuenow') === '51', 'Keyboard reduces report height');
  await page.keyboard.press('Home');
  check(await resize.getAttribute('aria-valuenow') === '30', 'Report height has lower bound');
  await page.keyboard.press('End');
  check(await resize.getAttribute('aria-valuenow') === '75', 'Report height has upper bound');
  const handle = await resize.boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await page.mouse.down();
  await page.mouse.move(handle.x + handle.width / 2, 396);
  await page.mouse.up();
  check(await resize.getAttribute('aria-valuenow') === '56', 'Pointer resizes report in place');
  check(Math.abs(await page.evaluate(() => window.scrollY) - reading) < 2, 'Resizing preserves reading offset');
  await page.locator('iframe[title="运行报告"]').evaluate(frame => { frame.contentWindow.__studyTest = 'retained'; });
  await page.frameLocator('iframe[title="运行报告"]').locator('#play').click();
  await page.getByRole('button', {name: '展开', exact: true}).click();
  check(await page.getByRole('dialog', {name: '阅读资料'}).isVisible(), 'Expanded workspace is accessible dialog');
  check(await page.locator('.page-wrapper').evaluate(el => el.inert), 'Expanded view prevents hidden reading focus');
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  check(await reportLink.evaluate(el => el === document.activeElement), 'Close restores report opener focus');
  check(!(await page.locator('.page-wrapper').evaluate(el => el.inert)), 'Close restores reading controls');
  check(await page.frameLocator('iframe[title="运行报告"]').locator('#play').textContent() === '播放', 'Hidden report pauses playback');
  await page.getByRole('link', {name: '交互图', exact: true}).click();
  await page.frameLocator('iframe[title="交互图"]').getByRole('button', {name: '下一步'}).click();
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  await reportLink.click();
  check(await page.locator('iframe[title="运行报告"]').evaluate(frame => frame.contentWindow.__studyTest === 'retained'), 'Reopening report retains loaded state');
  const functionSearch = page.frameLocator('iframe[title="运行报告"]').locator('#function-search');
  await functionSearch.fill('sys_yield');
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  await reportLink.click();
  check(await functionSearch.inputValue() === 'sys_yield', 'Reopening report retains actual function filter');
  check(await page.evaluate(() => {
    const frame = document.querySelector('iframe[title="运行报告"]');
    const doc = frame.contentDocument;
    doc.querySelector('nav.tabs button[data-tab="events"]').click();
    doc.querySelector('nav.tabs button[data-tab="functions"]').click();
    document.querySelector('.study-header button:last-child').click();
    document.querySelector('[data-study-resume]').click();
    return doc.querySelector('#function-search').value === 'sys_yield';
  }), 'Reopening restores filters synchronously after the report rebuilds its controls');
  await functionSearch.focus();
  await page.keyboard.press('Escape');
  check(!(await page.locator('.study-panel').isVisible()), 'Escape works inside report frame');
  for (const width of [320, 390, 900, 1200, 1720]) {
    await page.setViewportSize({width, height: 900});
    await reportLink.click();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Workspace fits ${width}px`);
    if (width <= 900) {
      check(await page.getByRole('dialog', {name: '阅读资料'}).isVisible(), 'Narrow workspace uses full screen');
      check(!(await page.getByRole('button', {name: '收起', exact: true}).isVisible()), 'Narrow workspace omits redundant expand control');
    }
    await page.getByRole('button', {name: '返回正文', exact: true}).click();
  }
  await page.setViewportSize({width: 1440, height: 900});
  await sections.selectOption('运行观察');
  await page.locator('main > p a[href*="/reports/"][href$=".html"]').first().click();
  check(await page.locator('.study-panel').isVisible(), 'In-text evidence link also opens workspace');
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  await page.goto(base + 'ch1/ucore.html');
  let requests = 0;
  await page.route('**/ucore-2026A-ch1-verified.html?*', async route => {
    requests++;
    if (requests === 1) await route.fulfill({status: 404, contentType: 'text/html', body: '<h1>Missing report</h1>'});
    else await route.continue();
  });
  await page.locator('.lesson-toolbar').getByRole('link', {name: '运行报告', exact: true}).click();
  await page.getByRole('button', {name: '重试', exact: true}).click();
  await page.frameLocator('iframe[title="运行报告"]').locator('#panel-functions.on').waitFor();
  check(requests === 2, 'Missing report can retry without losing reading page');
  await page.unroute('**/ucore-2026A-ch1-verified.html?*');
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  await page.goto(base + 'ch2/ucore.html');
  await sectionControl.selectOption('运行观察');
  const batchReading = await page.evaluate(() => window.scrollY);
  await page.locator('.lesson-toolbar').getByRole('link', {name: '运行报告', exact: true}).click();
  const reportChoices = page.getByRole('combobox', {name: '切换运行报告'});
  check(await reportChoices.locator('option').count() === 3, 'All chapter reports available without returning to text');
  const originalPath = await reportChoices.inputValue();
  const batchFrame = page.locator('.study-panel iframe:not([hidden])');
  await page.frameLocator('.study-panel iframe:not([hidden])').locator('#panel-functions.on').waitFor();
  await batchFrame.evaluate(frame => { frame.contentWindow.__studySwitch = 'retained'; });
  await reportChoices.focus();
  await reportChoices.selectOption({label: '异常批次'});
  await page.frameLocator('.study-panel iframe:not([hidden])').locator('#panel-functions.on').waitFor();
  check((await batchFrame.getAttribute('src')).includes('ch2-faults.html'), 'Switch displays selected workload');
  await reportChoices.selectOption(originalPath);
  check(await batchFrame.evaluate(frame => frame.contentWindow.__studySwitch === 'retained'), 'Switching back keeps prior report state');
  check(await reportChoices.evaluate(el => el === document.activeElement), 'Report switch keeps keyboard focus');
  check(await page.evaluate(() => window.scrollY) === batchReading, 'Report switch does not scroll the chapter');
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  await sectionControl.selectOption('系统调用与返回');
  await page.evaluate(() => window.scrollBy(0, 90));
  const exactPosition = await page.evaluate(() => window.scrollY);
  await page.reload();
  await page.waitForFunction(y => Math.abs(window.scrollY - y) < 2, exactPosition, {timeout: 5000}).catch(() => { throw new Error('Reload did not restore scroll position'); });
  await page.waitForFunction(() => document.querySelector('.lesson-outline [aria-current="location"]')?.dataset.section === '系统调用与返回', null, {timeout: 5000}).catch(() => { throw new Error('Reload did not restore section'); });
  await page.setViewportSize({width: 320, height: 740});
  await page.locator('.lesson-toolbar').getByRole('link', {name: '运行报告', exact: true}).click();
  check(await reportChoices.isVisible(), 'Report switch remains available on narrow screens');
  check(!(await resize.isVisible()), 'Full screen omits split-pane resize');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow report controls fit');
  const compactReport = page.frameLocator('.study-panel iframe:not([hidden])');
  await compactReport.locator('.study-run-information').waitFor();
  check(!(await compactReport.locator('.study-run-information').evaluate(el => el.open)), 'Narrow report starts with run metadata collapsed');
  await compactReport.getByText('运行信息与时间轴', {exact: true}).click();
  check(await compactReport.locator('.study-run-information').evaluate(el => el.open), 'Run information remains accessible');
  await compactReport.getByText('运行信息与时间轴', {exact: true}).click();
  check(await compactReport.locator('nav.tabs').evaluate(el => el.getBoundingClientRect().height < 65), 'Report tabs occupy one row on narrow screens');
  check(await compactReport.locator('nav.tabs button.on').evaluate(el => {
    const bounds = el.getBoundingClientRect();
    const tabs = el.parentElement.getBoundingClientRect();
    return bounds.left >= tabs.left && bounds.right <= tabs.right;
  }), 'Selected report tab is visible without horizontal searching');
  check(await compactReport.locator('#panel-functions').evaluate(el => el.getBoundingClientRect().top < 350), 'Narrow screen leaves room for recorded data');
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
}
