async (page) => {
  const check = (condition, label) => { if (!condition) throw new Error(label); };
  const base = await page.evaluate(() => new URL('./', location.href).href);
  await page.evaluate(() => {
    sessionStorage.removeItem('nodefusion-section-reading');
    sessionStorage.setItem('nodefusion-study-side', 'false');
  });
  await page.goto(base + 'ch5/rcore.html');
  check(await page.getByRole('button', {name: '逐节阅读', exact: true}).getAttribute('aria-pressed') === 'true', 'New readers start in section reading');
  check(await page.locator('main > h2:visible').count() === 1, 'New readers see one section');
  check(await page.locator('main > p').first().isVisible(), 'Source information stays visible in the first section');
  check(await page.getByLabel('当前小节位置', {exact: true}).textContent() === '1 / 6', 'Fixed navigation shows section progress');
  await page.getByRole('combobox', {name: '跳转到小节', exact: true}).selectOption('fork-与地址空间');
  check(!(await page.locator('main > p').first().isVisible()), 'Later sections do not repeat the introduction');
  check(await page.getByLabel('当前小节位置', {exact: true}).textContent() === '2 / 6', 'Section progress follows navigation');
  for (const width of [320, 390, 900, 1440]) {
    await page.setViewportSize({width, height: 900});
    await page.goto(base + 'ch4/rcore.html');
    const mode = page.getByRole('button', {name: '逐节阅读', exact: true});
    const select = page.getByRole('combobox', {name: '跳转到小节', exact: true});
    if (await mode.getAttribute('aria-pressed') === 'true') await mode.click();
    await select.selectOption('映射与回收');
    const before = await page.locator('main > h2[id="映射与回收"]').evaluate(el => el.getBoundingClientRect().top);
    await mode.click();
    check(await mode.getAttribute('aria-pressed') === 'true', 'Section reading selected');
    check(await page.locator('main > h2:visible').count() === 1, 'Only the selected section is displayed');
    check(Math.abs(await page.locator('main > h2[id="映射与回收"]').evaluate(el => el.getBoundingClientRect().top) - before) < 3, 'Changing mode preserves reading anchor');
    const paging = page.getByRole('navigation', {name: '小节前后导航'});
    await paging.getByRole('button').last().click();
    check(await select.inputValue() === '运行观察', 'Section footer goes directly to next section');
    check(await page.locator('main > h2[id="运行观察"]').evaluate(el => el === document.activeElement), 'Footer navigation moves focus to new heading');
    check(await paging.getByRole('button').last().isDisabled(), 'Last section has no next section');
    await page.reload();
    check(await mode.getAttribute('aria-pressed') === 'true', 'Reading mode survives refresh');
    check(await select.inputValue() === '运行观察', 'Refresh restores selected section');
    check(await page.locator('main > h2:visible').count() === 1, 'Refresh does not reveal unrelated sections');
    await page.evaluate(() => { location.hash = '用户地址检查'; });
    await page.waitForFunction(() => document.querySelector('.lesson-section select').value === '用户地址检查');
    check(await page.locator('main > h2[id="用户地址检查"]').isVisible(), 'Fragment navigation reveals hidden section');
    await select.selectOption({index: 0});
    check(await paging.getByRole('button').first().isDisabled(), 'First section has no previous section');
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Section layout fits ${width}px`);
    check(await select.evaluate(el => el.getBoundingClientRect().width >= 120), 'Section selector retains readable space on narrow screens');
    check(await page.locator('main > h2:visible').evaluate(el => el.getBoundingClientRect().top >= document.querySelector('.lesson-toolbar').getBoundingClientRect().bottom - 1), 'Heading is below fixed navigation');
    await mode.click();
    check(await page.locator('main > h2:visible').count() === 6, 'Continuous reading restores full content');
  }
  await page.setViewportSize({width: 320, height: 256});
  await page.goto(base + 'ch4/rcore.html');
  await page.getByRole('combobox', {name: '跳转到小节', exact: true}).selectOption('运行观察');
  check(await page.locator('.lesson-toolbar').evaluate(el => getComputedStyle(el).position === 'static'), 'Short viewports release fixed chapter controls');
  check(await page.locator('main > h2[id="运行观察"]').evaluate(el => el.getBoundingClientRect().top >= 50 && el.getBoundingClientRect().top < 100), 'Short viewport keeps the destination visible');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Short viewport reflows without horizontal page scrolling');
  await page.setViewportSize({width: 1440, height: 900});
  await page.goto(base + 'ch3/rcore.html');
  const mode = page.getByRole('button', {name: '逐节阅读', exact: true});
  await mode.click();
  const select = page.getByRole('combobox', {name: '跳转到小节', exact: true});
  await select.selectOption('让出与选择下一个任务');
  await page.getByRole('link', {name: 'uCore', exact: true}).first().click();
  check(await select.inputValue() === '让出处理器', 'Implementation switch keeps matching mechanism');
  check(await mode.getAttribute('aria-pressed') === 'true', 'Implementation switch keeps reading mode');
  await page.getByRole('button', {name: '对照阅读', exact: true}).click();
  await page.getByRole('complementary', {name: 'rCore 对照阅读'}).getByRole('heading').first().waitFor();
  await select.selectOption('运行观察');
  await page.getByRole('complementary', {name: 'rCore 对照阅读'}).getByRole('heading', {name: '运行观察', exact: true}).waitFor();
  await page.getByRole('button', {name: '关闭对照阅读'}).click();
  const y = await page.evaluate(() => window.scrollY);
  await page.getByRole('link', {name: '运行报告', exact: true}).click();
  await page.frameLocator('iframe[title="运行报告"]').locator('#panel-functions.on').waitFor();
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  check(Math.abs(await page.evaluate(() => window.scrollY) - y) < 2, 'Report round trip keeps section reading offset');
  await page.emulateMedia({media: 'print'});
  check(await page.locator('main > h2:visible').count() > 1, 'Print includes every section');
  check(!(await page.locator('.lesson-comparison').isVisible()), 'Print excludes comparison controls');
  await page.emulateMedia({media: 'screen'});
  await mode.click();
  await select.selectOption('运行观察');
  await page.getByRole('link', {name: '运行报告', exact: true}).click();
  const evidence = page.locator('main > p a').filter({hasText: '打开'}).first();
  await evidence.focus();
  check(await evidence.evaluate(el => {
    const bounds = el.getBoundingClientRect();
    return bounds.top >= document.querySelector('.lesson-toolbar').getBoundingClientRect().bottom &&
      bounds.bottom <= document.querySelector('.study-panel').getBoundingClientRect().top;
  }), 'Keyboard focus is not hidden behind reading or report controls');
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  await page.goto(base + 'ch4/ucore.html#运行观察');
  await page.goto(base);
  await page.setViewportSize({width: 320, height: 720});
  await page.goto(base + 'ch4/ucore.html#运行观察');
  await page.waitForFunction(() => document.querySelector('.lesson-section select').value === '运行观察');
  check(await page.locator('main > h2[id="运行观察"]').evaluate(el => Math.abs(el.getBoundingClientRect().top - parseFloat(document.querySelector('main').style.getPropertyValue('--lesson-offset'))) < 3), 'Changed line width restores the section rather than stale pixel offsets');
  const withoutStorage = await page.context().newPage();
  await withoutStorage.addInitScript(() => {
    Object.defineProperty(window, 'sessionStorage', {get() { throw new Error('Storage disabled'); }});
  });
  await withoutStorage.goto(base + 'ch4/rcore.html');
  check(await withoutStorage.getByRole('button', {name: '逐节阅读', exact: true}).getAttribute('aria-pressed') === 'true', 'Default reading mode also works without storage');
  await withoutStorage.getByRole('combobox', {name: '跳转到小节', exact: true}).selectOption('运行观察');
  check(await withoutStorage.locator('main > h2:visible').count() === 1, 'Section reading works without storage');
  await withoutStorage.close();
  const noScript = await page.context().browser().newContext({javaScriptEnabled: false});
  const fallback = await noScript.newPage();
  await fallback.goto(base + 'ch4/rcore.html');
  check(await fallback.locator('main > h2:visible').count() === 6, 'All content remains readable without JavaScript');
  await noScript.close();
}
