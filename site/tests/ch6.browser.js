async (page) => {
  const check = (condition, label) => { if (!condition) throw new Error(label); };
  const base = await page.evaluate(() => new URL('./', location.href).href);
  await page.evaluate(() => { sessionStorage.setItem('nodefusion-section-reading', 'true'); sessionStorage.setItem('nodefusion-study-side', 'false'); });
  for (const width of [320, 390, 900, 1440]) {
    await page.setViewportSize({width, height: 900});
    await page.goto(base + 'ch6/rcore.html');
    const select = page.getByRole('combobox', {name: '跳转到小节', exact: true});
    check(await select.locator('option').count() === 7, 'Chapter has seven mechanism sections');
    await select.selectOption('数据块与磁盘布局');
    const y = await page.evaluate(() => scrollY);
    await page.getByRole('link', {name: '交互图', exact: true}).click();
    const diagram = page.frameLocator('iframe[title="交互图"]');
    await diagram.getByRole('spinbutton', {name: '字节偏移'}).waitFor();
    await diagram.getByRole('button', {name: '二级间接起点'}).click();
    check(await diagram.getByRole('spinbutton').inputValue() === '79360', 'Boundary uses actual rCore layout');
    check((await diagram.locator('#result').textContent()).includes('逻辑块 155'), 'Double-indirect boundary gives logical block 155');
    check(await diagram.locator('#block-path .node').count() === 4, 'Double-indirect path shows both index blocks');
    await diagram.getByRole('spinbutton').fill('8467967');
    check((await diagram.locator('#result').textContent()).includes('余数 511'), 'Last byte has correct within-block offset');
    check(await diagram.locator('#block-path').textContent().then(text => (text.match(/地址项 \[127\]/g) || []).length === 2), 'Last rCore block uses both final index entries');
    await diagram.getByRole('spinbutton').fill('8467968');
    check(await diagram.getByRole('spinbutton').getAttribute('aria-invalid') === 'true', 'Capacity overflow is accessible validation error');
    check(await diagram.locator('#block-path .node').count() === 0, 'Invalid input removes stale lookup path');
    await diagram.getByRole('combobox', {name: '内核', exact: true}).selectOption('ucore');
    await diagram.getByRole('button', {name: '一级间接起点'}).click();
    check(await diagram.getByRole('spinbutton').inputValue() === '12288', 'C layout has different direct boundary');
    check(await diagram.locator('#block-path .node').count() === 3, 'C path has one indirect index block');
    check(await diagram.getByRole('spinbutton').getAttribute('aria-invalid') === 'false', 'Valid boundary clears input error');
    check(await page.locator('iframe[title="交互图"]').evaluate(frame => frame.contentDocument.documentElement.scrollWidth <= frame.contentWindow.innerWidth), 'Diagram reflows in embedded reading workspace');
    await diagram.getByRole('link', {name: '返回第六章正文'}).click();
    check(await select.inputValue() === '数据块与磁盘布局', 'Diagram returns to mechanism section');
    check(Math.abs(await page.evaluate(() => scrollY) - y) < 2, 'Diagram round trip preserves reading position');
    await page.getByRole('link', {name: 'uCore', exact: true}).first().click();
    check(await select.inputValue() === '数据块与磁盘布局', 'Implementation switch stays on corresponding mechanism');
    await select.selectOption('运行观察');
    await page.getByRole('link', {name: '运行报告', exact: true}).click();
    const report = page.frameLocator('.study-panel iframe:not([hidden])');
    await report.locator('#panel-functions.on').waitFor();
    await report.locator('#function-search').fill('virtio_disk_intr');
    check((await report.locator('.function-sequence').textContent()).includes('virtio_disk_intr'), 'Actual C trace has interrupt completion entry');
    await page.getByRole('button', {name: '返回正文', exact: true}).click();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Chapter fits ${width}px`);
  }
  await page.setViewportSize({width: 1440, height: 900});
  await page.goto(base + 'ch6/rcore.html#运行观察');
  await page.getByRole('link', {name: '运行报告', exact: true}).click();
  const choices = page.getByRole('combobox', {name: '切换运行报告'});
  await choices.selectOption({label: '打开扩展测试报告'});
  const report = page.frameLocator('.study-panel iframe:not([hidden])');
  await report.locator('#panel-functions.on').waitFor();
  await report.locator('#function-search').fill('clear_inode_data');
  check((await report.locator('.function-sequence').textContent()).includes('clear_inode_data'), 'Actual extended trace exposes disk block reclamation');
  await page.getByRole('button', {name: '返回正文', exact: true}).click();
  await page.goto(base + 'ch6/index.html');
  await page.getByRole('combobox', {name: '跳转到小节', exact: true}).selectOption('文件名与文件描述符');
  check(await page.locator('main img').first().evaluate(img => img.complete && img.naturalWidth > 0), 'File-object diagram loads');
  check(await page.locator('main img').first().evaluate(img => img.getBoundingClientRect().width >= document.querySelector('main').getBoundingClientRect().width * .95), 'File-object diagram uses the available reading width');
  const context = await page.context().browser().newContext({javaScriptEnabled: false});
  const fallback = await context.newPage();
  await fallback.goto(base + 'diagrams/ch6-blocks.html');
  check(await fallback.locator('#static-diagram').evaluate(el => el.open), 'Static lookup diagram is expanded without scripts');
  check(await fallback.locator('#static-diagram img').evaluate(img => img.complete && img.naturalWidth > 0), 'Static lookup diagram remains readable');
  await context.close();
}
